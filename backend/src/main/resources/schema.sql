-- ============================================================================
-- CTI Insights
-- Esquema do banco PostgreSQL
-- Azure Database for PostgreSQL - Servidor Flexível
--
-- Executado automaticamente pelo Spring Boot na inicialização.
--
-- O Spring Boot gerencia os usuários e tokens revogados.
-- Os dados dos uploads são gravados pelo Python.
--
-- Atualizações:
-- 1. Controle de versão da sessão JWT.
-- 2. Revogação individual de JWT após logout.
-- ============================================================================

-- ============================================================================
-- 1. USUÁRIOS
-- Cadastro, login, perfil e liberação de acesso
-- ============================================================================

CREATE TABLE IF NOT EXISTS usuario (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nome VARCHAR(120) NOT NULL,

    email VARCHAR(160) NOT NULL UNIQUE,

    senha_hash VARCHAR(100) NOT NULL,

    matricula VARCHAR(30),

    turma VARCHAR(60),

    perfil VARCHAR(20) NOT NULL DEFAULT 'USER',

    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',

    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Invalida sessões antigas após mudança da versão.
    versao_sessao BIGINT NOT NULL DEFAULT 0

);

-- Compatibilidade com bancos criados anteriormente.
-- Preserva os usuários e as senhas existentes.

ALTER TABLE usuario
ADD COLUMN IF NOT EXISTS versao_sessao BIGINT NOT NULL DEFAULT 0;

-- ============================================================================
-- 2. LOTES
-- Cada envio de planilha corresponde a um lote.
-- Criado e gravado pelo Python.
-- ============================================================================

CREATE TABLE IF NOT EXISTS upload_lote (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    arquivo_nome VARCHAR(255) NOT NULL,

    enviado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    status VARCHAR(20) NOT NULL,

    total_linhas INT NOT NULL DEFAULT 0,

    linhas_validas INT NOT NULL DEFAULT 0,

    linhas_invalidas INT NOT NULL DEFAULT 0,

    linhas_com_aviso INT NOT NULL DEFAULT 0,

    mensagem VARCHAR(500)

);

-- ============================================================================
-- 3. CONSULTOR
-- Cadastro de consultores sem duplicação.
-- ============================================================================

CREATE TABLE IF NOT EXISTS consultor (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nome VARCHAR(120) NOT NULL UNIQUE

);

-- ============================================================================
-- 4. SEGMENTO
-- Segmentos de mercado padronizados.
-- ============================================================================

CREATE TABLE IF NOT EXISTS segmento (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nome VARCHAR(40) NOT NULL UNIQUE

);

-- ============================================================================
-- 5. SERVIÇO
-- Serviços oferecidos pelo provedor.
-- ============================================================================

CREATE TABLE IF NOT EXISTS servico (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nome VARCHAR(120) NOT NULL UNIQUE

);

-- ============================================================================
-- 6. CLIENTE
-- Armazena os clientes válidos após o processamento.
-- ============================================================================

CREATE TABLE IF NOT EXISTS cliente (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    lote_id BIGINT NOT NULL
        REFERENCES upload_lote(id)
        ON DELETE CASCADE,

    codigo_cti VARCHAR(60) NOT NULL,

    nome VARCHAR(255) NOT NULL,

    consultor_id BIGINT NOT NULL
        REFERENCES consultor(id),

    segmento_id BIGINT NOT NULL
        REFERENCES segmento(id),

    nivel CHAR(1) NOT NULL,

    faturamento_anual NUMERIC(16,2) NOT NULL,

    cidade VARCHAR(120),

    uf CHAR(2),

    UNIQUE (lote_id, codigo_cti)

);

-- ============================================================================
-- 7. CONTRATO
-- Relaciona clientes aos serviços contratados.
-- ============================================================================

CREATE TABLE IF NOT EXISTS contrato (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    cliente_id BIGINT NOT NULL
        REFERENCES cliente(id)
        ON DELETE CASCADE,

    servico_id BIGINT NOT NULL
        REFERENCES servico(id),

    data_contratacao DATE NOT NULL,

    UNIQUE (cliente_id, servico_id)

);

-- ============================================================================
-- 8. ESTATÍSTICAS DOS LOTES
-- Resultados usados nos relatórios e gráficos.
-- ============================================================================

CREATE TABLE IF NOT EXISTS estatistica_lote (

    lote_id BIGINT PRIMARY KEY
        REFERENCES upload_lote(id)
        ON DELETE CASCADE,

    gerado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    resultado TEXT NOT NULL

);

-- ============================================================================
-- 9. TOKENS JWT REVOGADOS
--
-- Cada JWT possui um identificador único (jti).
--
-- Quando o usuário realiza logout:
-- 1. O backend registra o jti nesta tabela.
-- 2. O filtro de autenticação verifica se o jti está revogado.
-- 3. Tokens revogados não podem autenticar novamente.
--
-- A expiração permite a limpeza futura dos registros.
--
-- Não altera a tabela usuario.
-- Não remove sessões de outros navegadores.
-- ============================================================================

CREATE TABLE IF NOT EXISTS token_revogado (

    jti VARCHAR(36) PRIMARY KEY,

    expira_em TIMESTAMP(6) WITH TIME ZONE NOT NULL

);

-- Índice para futuras rotinas de limpeza dos tokens que já expiraram.

CREATE INDEX IF NOT EXISTS idx_token_revogado_expira_em
    ON token_revogado (expira_em);